import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('[pageerror] ' + e.message + '\n' + (e.stack || '')));
await page.route('**/*', (r) => (r.request().url().startsWith('file:') ? r.continue() : r.abort()));
await page.goto(pathToFileURL(resolve('versions/yard-zero-v0.1.html')).href);
await page.waitForFunction(() => window.__yz, null, { timeout: 60000 });
const wait = (ms) => page.waitForTimeout(ms);
const ev = (fn, arg) => page.evaluate(fn, arg);
await wait(1000);
await page.screenshot({ path: 'test/40-menu.png' });
await ev(() => { window.__yz.dbg.noDyn = true; document.getElementById('btnStart').click(); });
await wait(1000);
await ev(() => {
  const y = window.__yz; y.game.between = 999;
  y.player.pos.set(-6, 0, 22); y.player.yaw = 0.3; y.player.pitch = -0.03;
  const e = y.spawnEnemy(-8.3, 14.2); e.state = 'combat'; e.react = 99; e.tactic = 99; e.canSee = true; e.seeT = 99; e.lastKnown.copy(y.player.pos);
});
await wait(1500);
await ev(() => { const y = window.__yz; const e = y.enemies[0], c = y.camera.position; const dx = e.pos.x - c.x, dz = e.pos.z - c.z; y.player.yaw = Math.atan2(-dx, -dz); y.player.pitch = Math.atan2(1.4 - c.y, Math.hypot(dx, dz)); y.input.fire = true; });
await wait(350);
await page.screenshot({ path: 'test/41-fire.png' });
await ev(() => { window.__yz.input.fire = false; });
console.log(errors.length ? 'ERRORS:\n' + [...new Set(errors)].join('\n') : 'no errors');
await browser.close();
